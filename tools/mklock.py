"""Turn a `pip install --dry-run --report` JSON into exact pins (backend/requirements.lock).

Usage: python tools/mklock.py .lock.json backend/requirements.lock
The project itself (direct/editable install) is left out."""

import json
import sys
from pathlib import Path


def pins(report: dict) -> list[str]:  # type: ignore[type-arg]
    out = {}
    for it in report["install"]:
        if it.get("is_direct"):
            continue
        m = it["metadata"]
        out[m["name"].lower().replace("_", "-")] = m["version"]
    return [f"{k}=={v}" for k, v in sorted(out.items())]


def main(argv: list[str]) -> int:
    rep, dst = Path(argv[1]), Path(argv[2])
    lines = pins(json.loads(rep.read_text()))
    dst.write_text("# generated by `make lock` (tools/mklock.py); do not edit\n" + "\n".join(lines) + "\n")
    print(f"{len(lines)} pins -> {dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
